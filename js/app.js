/* =========================================================================
   시작 처리 · 화면 1(처음 설정 / API 키) (app.js)
   -------------------------------------------------------------------------
   ★ 보안 : API 키는 어떤 경우에도 console 에 찍지 않습니다.
     화면에 보여줄 때도 앞뒤 몇 글자만 남기고 가립니다.
   ========================================================================= */

(function () {

  var 요소 = UI.요소;

  /* 설정 화면의 상태 : '없음' | '보기' | '변경' */
  var 설정상태 = '없음';

  /* =====================================================================
     1. 앱 시작
     ===================================================================== */
  function 시작() {
    // 맨 아래 고정 안내 문구
    요소('바닥안내').textContent = CONFIG.FOOTER_NOTICE;

    연결하기();
    Docs.초기화();

    DB.open().then(function (아이디비성공) {
      if (!아이디비성공) {
        UI.쪽지('저장 공간을 쓸 수 없어 간이 저장으로 동작합니다.', '오류');
      }

      if (DB.hasApiKey()) {
        설정상태맞추기('보기');
        UI.탭잠금(false);
        UI.화면보이기('채팅');
      } else {
        설정상태맞추기('없음');
        UI.탭잠금(true);
        UI.화면보이기('설정');
      }
    });
  }

  /* =====================================================================
     2. 버튼·탭 연결
     ===================================================================== */
  function 연결하기() {
    // 상단 탭 3개
    document.getElementById('탭들').addEventListener('click', function (e) {
      var 탭 = e.target.closest('.탭');
      if (!탭 || 탭.disabled) return;

      if (!DB.hasApiKey()) {
        UI.쪽지('API 키를 먼저 등록해 주세요.', '오류');
        UI.화면보이기('설정');
        return;
      }
      UI.화면보이기(탭.dataset.화면);
      if (탭.dataset.화면 === '자료') Docs.자료목록그리기();
    });

    // 맨 위 [키 설정] 버튼
    요소('키설정열기').addEventListener('click', function () {
      설정상태맞추기(DB.hasApiKey() ? '보기' : '없음');
      UI.화면보이기('설정');
    });

    // 키 보이기 / 가리기
    요소('키보기').addEventListener('click', 키보기전환);

    // 저장 / 변경 / 변경취소 / 삭제
    요소('키저장').addEventListener('click', 키저장하기);
    요소('키변경').addEventListener('click', function () { 설정상태맞추기('변경'); });
    요소('키변경취소').addEventListener('click', function () { 설정상태맞추기('보기'); });
    요소('키삭제').addEventListener('click', 키삭제하기);

    // 입력칸에서 엔터를 치면 저장
    요소('키입력').addEventListener('keydown', function (e) {
      if (e.key === 'Enter') { e.preventDefault(); 키저장하기(); }
    });

    // 다시 입력하기 시작하면 빨간 표시를 지운다
    요소('키입력').addEventListener('input', function () {
      요소('키입력').classList.remove('오류');
      도움말쓰기('키는 화면에 ●●● 로 가려져 표시됩니다. 오른쪽 눈 모양을 누르면 확인할 수 있습니다.', '');
    });
  }

  /* =====================================================================
     3. 설정 화면 상태 바꾸기
     ===================================================================== */
  function 설정상태맞추기(상태) {
    설정상태 = 상태;

    var 있음   = (상태 !== '없음');
    var 변경중 = (상태 === '변경');

    요소('키상태').classList.toggle('숨김', !있음);
    요소('키변경').classList.toggle('숨김', !있음 || 변경중);
    요소('키변경취소').classList.toggle('숨김', !변경중);
    요소('키삭제').classList.toggle('숨김', !있음);
    요소('키저장').classList.toggle('숨김', 있음 && !변경중);

    요소('키저장').textContent = 변경중 ? '새 키로 저장' : '키 저장하고 시작하기';

    // 머리말 문구
    if (상태 === '없음') {
      요소('설정배지').textContent = '처음 오셨나요?';
      요소('설정제목').innerHTML = '구글 Gemini API 키를 등록하면<br>사내 규정 챗봇이 열립니다';
    } else {
      요소('설정배지').textContent = '등록 완료';
      요소('설정제목').innerHTML = '키가 등록되어 있습니다<br>바로 질문하실 수 있습니다';
    }

    // 저장된 키를 가려서 보여준다
    if (있음) 요소('가린키').textContent = 키가리기(DB.getApiKey());

    // 입력칸
    var 입력 = 요소('키입력');
    입력.value = '';
    입력.type = 'password';
    눈아이콘맞추기(false);

    if (있음 && !변경중) {
      입력.disabled = true;
      입력.placeholder = '저장된 키를 사용 중입니다';
      도움말쓰기('키를 바꾸려면 [키 변경]을, 이 컴퓨터에서 지우려면 [키 삭제]를 누르세요.', '');
    } else {
      입력.disabled = false;
      입력.placeholder = 'AIza… 로 시작하는 키를 붙여넣으세요';
      입력.classList.remove('오류');
      도움말쓰기('키는 화면에 ●●● 로 가려져 표시됩니다. 오른쪽 눈 모양을 누르면 확인할 수 있습니다.', '');
      if (변경중) setTimeout(function () { 입력.focus(); }, 30);
    }
  }

  /* 키를 앞 4글자 · 뒤 4글자만 남기고 가린다. 예) AIza••••••••••3f9K */
  function 키가리기(키) {
    if (!키) return '';
    if (키.length <= 10) return '••••••••';
    return 키.slice(0, 4) + '••••••••••' + 키.slice(-4);
  }

  /* =====================================================================
     4. 키 보이기 / 가리기
     ===================================================================== */
  function 키보기전환() {
    var 입력 = 요소('키입력');
    if (입력.disabled) return;

    var 보이게할까 = (입력.type === 'password');
    입력.type = 보이게할까 ? 'text' : 'password';
    눈아이콘맞추기(보이게할까);
    입력.focus();
  }

  function 눈아이콘맞추기(보이는중) {
    var 버튼 = 요소('키보기');
    버튼.setAttribute('aria-pressed', 보이는중 ? 'true' : 'false');
    버튼.setAttribute('aria-label', 보이는중 ? '키 가리기' : '키 보이기');

    // 보이는 중이면 눈에 빗금이 그어진 아이콘으로 바꾼다.
    요소('눈아이콘').innerHTML = 보이는중
      ? '<path d="M17.94 17.94A10.07 10.07 0 0 1 12 20c-7 0-11-8-11-8a18.45 18.45 0 0 1 5.06-5.94"></path>' +
        '<path d="M9.9 4.24A9.12 9.12 0 0 1 12 4c7 0 11 8 11 8a18.5 18.5 0 0 1-2.16 3.19"></path>' +
        '<path d="M9.88 9.88a3 3 0 1 0 4.24 4.24"></path>' +
        '<line x1="1" y1="1" x2="23" y2="23"></line>'
      : '<path d="M1 12s4-8 11-8 11 8 11 8-4 8-11 8-11-8-11-8z"></path>' +
        '<circle cx="12" cy="12" r="3"></circle>';
  }

  /* =====================================================================
     5. 키 저장 / 삭제
     ===================================================================== */
  function 도움말쓰기(글, 종류) {
    var 곳 = 요소('키도움말');
    곳.textContent = 글;
    곳.className = '도움말' + (종류 ? ' ' + 종류 : '');
  }

  function 키저장하기() {
    var 입력 = 요소('키입력');
    // 눈에 보이지 않는 공백·줄바꿈은 붙여넣기 사고이므로 조용히 없앤다.
    var 값 = 입력.value.replace(/[\s\u200B-\u200D\uFEFF]/g, '');

    if (값.length === 0) {
      입력.classList.add('오류');
      도움말쓰기('키를 붙여넣어 주세요. 위 1번 안내대로 구글 AI 스튜디오에서 받을 수 있습니다.', '오류');
      입력.focus();
      return;
    }

    if (값.length < 20) {
      입력.classList.add('오류');
      도움말쓰기('키가 너무 짧습니다. 키 전체가 복사되었는지 확인한 뒤 다시 붙여넣어 주세요.', '오류');
      입력.focus();
      return;
    }

    DB.saveApiKey(값);

    // 구글 키는 보통 AIza 로 시작한다. 아니어도 저장은 하되 한 번 알려 준다.
    var 안내 = (값.indexOf('AIza') === 0)
      ? '키를 저장했습니다.'
      : '키를 저장했습니다. 다만 구글 API 키는 보통 AIza 로 시작합니다. 답변이 되지 않으면 키를 다시 확인해 주세요.';

    var 처음등록 = (설정상태 === '없음');

    입력.value = '';
    설정상태맞추기('보기');
    UI.탭잠금(false);
    도움말쓰기(안내, '성공');
    UI.쪽지('키를 저장했습니다. 이제 질문할 수 있습니다.');

    // 처음 등록한 경우에는 바로 질문하기 화면으로 넘어간다.
    if (처음등록) UI.화면보이기('채팅');
  }

  function 키삭제하기() {
    var 확인 = window.confirm(
      '이 브라우저에 저장된 API 키를 지웁니다.\n' +
      '등록한 규정 자료와 대화 내용은 지워지지 않습니다.\n\n지울까요?'
    );
    if (!확인) return;

    DB.deleteApiKey();
    설정상태맞추기('없음');
    UI.탭잠금(true);
    UI.화면보이기('설정');
    도움말쓰기('키를 지웠습니다. 다시 사용하려면 새 키를 붙여넣어 주세요.', '');
    UI.쪽지('키를 지웠습니다.');
  }

  /* ---- 문서가 준비되면 시작 ---- */
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', 시작);
  } else {
    시작();
  }
})();
